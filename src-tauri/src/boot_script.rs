//! Generate the small ESM launcher that boots the official **desktop** profile.
//!
//! The CLI refuses --profile desktop (only plugin subcommands may manage it),
//! so the shell calls 'runProfile' directly through the package's 'profile-boot'
//! subpath - the same private entry the official Electron host uses. Everything
//! generated here lives under <DSH_HOME>/dsh-tauri/boot/; nothing is ever
//! written into the npm runtime tree.

use std::fs;
use std::path::{Path, PathBuf};

use serde_json::json;

/// Environment variable carrying the launcher configuration as one JSON object.
/// The generated script only parses it; no shell value is pasted into JS source.
pub const BOOT_CONFIG_ENV: &str = "DSH_TAURI_BOOT_CONFIG";
/// Version reported to the upstream telemetry row by the shell process.
pub const CLIENT_VERSION_ENV: &str = "DSH_CLIENT_VERSION";

const BOOT_DIR: &str = "dsh-tauri/boot";
const BOOT_FILE: &str = "dsh-tauri-profile-boot.mjs";
const PATCH_FILE: &str = "dsh-tauri.runtime.patch.json";
const LINK_NAME: &str = "node_modules";
/// Bump when the generated import graph or argument shape changes.
const GENERATION: u32 = 1;

/// Inputs the launcher needs. All values travel to the script through
/// DSH_TAURI_BOOT_CONFIG, never through string interpolation.
pub struct BootConfig<'a> {
    pub profile: &'a str,
    pub profile_dir: &'a Path,
    pub host: &'a str,
    pub desktop_version: &'a str,
    /// Absolute path of a pnpm executable, when one is available.
    pub pnpm: Option<&'a Path>,
}

/// Stable digest of the generation inputs, used in the header so a changed
/// configuration visibly produces a different file (and therefore a rewrite).
fn content_digest(config: &BootConfig<'_>) -> String {
    let pnpm = config.pnpm.map(|path| path.to_string_lossy().into_owned()).unwrap_or_default();
    let payload = format!(
        "{}\u{1f}{}\u{1f}{}\u{1f}{}\u{1f}{}\u{1f}{}",
        GENERATION, config.profile, config.profile_dir.display(), config.host, pnpm, config.desktop_version
    );
    // FNV-1a 64: dependency-free and deterministic; this is an identity tag,
    // not a security primitive.
    let mut hash = 0xcbf2_9ce4_8422_2325_u64;
    for byte in payload.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}

/// Render the .mjs launcher. Pure: no filesystem, environment or process access.
///
/// The imports resolve through a node_modules symlink created next to the
/// script by ensure_module_link, so the bare package subpaths stay exactly
/// the ones the upstream package exports.
pub fn render_boot_script(config: &BootConfig<'_>) -> String {
    let pnpm_absent = if config.pnpm.is_none() { "true" } else { "false" };
    format!(
        "// Generated by dsh-tauri boot generator v{GENERATION} ({digest}).\n\
         // Do not edit: regenerated on every launch from the shell configuration.\n\
         import {{ runProfile, INSTALL_ANCHOR }} from '@deepseek-ai/dsh/profile-boot';\n\
         import {{ loadProfileDirectory }} from '@deepseek-ai/dsh-app-boot';\n\
         import {{ createLaunchEnvironmentSnapshot }} from '@deepseek-ai/dsh-launch-environment';\n\
         \n\
         const config = JSON.parse(process.env.{env});\n\
         const environment = createLaunchEnvironmentSnapshot([\n\
         \x20 {{ source: 'process', values: {{ ...process.env }} }},\n\
         ]);\n\
         const profile = loadProfileDirectory(\n\
         \x20 config.profileName, config.profileDir, INSTALL_ANCHOR, {{ userLayer: true }}\n\
         );\n\
         const resolvedProfile = {{ profile, installAnchor: INSTALL_ANCHOR }};\n\
         const packageManager = {pnpm_absent}\n\
         \x20 ? undefined\n\
         \x20 : {{ command: config.pnpm, args: [], env: {{ ...process.env }} }};\n\
         \n\
         await runProfile({{\n\
         \x20 environment,\n\
         \x20 profile: config.profileName,\n\
         \x20 resolvedProfile,\n\
         \x20 patchFiles: [config.runtimePatch],\n\
         \x20 args: ['--host', config.host, '--port', '0', '--no-open'],\n\
         \x20 ...(packageManager === undefined ? {{}} : {{ packageManager }}),\n\
         }});\n",
        digest = content_digest(config),
        env = BOOT_CONFIG_ENV,
    )
}

/// Render the JSON payload passed through the environment. Keeping it here
/// makes it impossible for the supervisor to forget one of the boot fields.
pub fn render_boot_config(config: &BootConfig<'_>, patch: &Path) -> String {
    json!({
        "profileName": config.profile,
        "profileDir": config.profile_dir,
        "host": config.host,
        "runtimePatch": patch,
        "pnpm": config.pnpm,
    })
    .to_string()
}

/// Directory that owns every generated file. Never inside the npm runtime.
pub fn boot_dir(home: &Path) -> PathBuf {
    home.join(BOOT_DIR)
}

/// Absolute path of the generated launcher.
#[allow(dead_code)]
pub fn boot_script_path(home: &Path) -> PathBuf {
    boot_dir(home).join(BOOT_FILE)
}

/// Absolute path of the generated patch file for a given Harness home.
pub fn runtime_patch_path(home: &Path) -> PathBuf {
    boot_dir(home).join(PATCH_FILE)
}

/// Minimal overlay applied on top of the profile's own patch layers.
///
/// The official host writes five LAN addresses into connection.trustedHosts;
/// this shell is strictly loopback-only, so the list is empty. Home and
/// profile patches are loaded by runProfile itself and are never duplicated.
pub fn render_runtime_patch(desktop_version: &str) -> String {
    let patch = json!([
        {
            "id": "desktop-next-webserver",
            "config": { "host": "127.0.0.1", "port": 0 }
        },
        {
            "id": "connection",
            "config": { "trustedHosts": [] }
        },
        {
            "id": "desktop-product-telemetry",
            "config": {
                "serviceName": "deepseek-harness-desktop",
                "serviceVersion": desktop_version
            }
        }
    ]);
    format!("{}\n", serde_json::to_string_pretty(&patch).unwrap_or_else(|_| patch.to_string()))
}

/// Write only when the bytes differ, through a same-directory temp file and
/// rename so a concurrent launch or a kill mid-write cannot leave a torn file.
fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == content) {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|error| format!("无法创建启动脚本目录 {}: {error}", parent.display()))?;
    }
    let mut staging = path.as_os_str().to_os_string();
    staging.push(format!(".tmp-{}", std::process::id()));
    let staging = PathBuf::from(staging);
    fs::write(&staging, content)
        .and_then(|()| fs::rename(&staging, path))
        .map_err(|error| {
            let _ = fs::remove_file(&staging);
            format!("无法原子写入 {}: {error}", path.display())
        })
}

/// Generate (or refresh, when its content changed) the launcher script.
pub fn write_boot_script(dir: &Path, content: &str) -> Result<PathBuf, String> {
    let path = dir.join(BOOT_FILE);
    write_if_changed(&path, content)?;
    Ok(path)
}

/// Generate (or refresh) the minimal runtime patch overlay.
pub fn write_runtime_patch(dir: &Path, content: &str) -> Result<PathBuf, String> {
    let path = dir.join(PATCH_FILE);
    write_if_changed(&path, content)?;
    Ok(path)
}

/// Bare ESM imports need a node_modules directory visible from the generated
/// script. A symlink next to it keeps all writes outside the npm runtime tree
/// and follows runtime updates automatically.
pub fn ensure_module_link(dir: &Path, runtime: &Path) -> Result<PathBuf, String> {
    let link = dir.join(LINK_NAME);
    let target = runtime.join("node_modules");
    if !target.is_dir() {
        return Err(format!("运行时缺少 node_modules 目录：{}", target.display()));
    }
    fs::create_dir_all(dir).map_err(|error| format!("无法创建启动脚本目录 {}: {error}", dir.display()))?;
    if let Ok(existing) = fs::read_link(&link) {
        if existing == target {
            return Ok(link);
        }
        // Stale link (e.g. after a runtime update): replace it, never follow it.
        fs::remove_file(&link)
            .map_err(|error| format!("无法移除旧模块链接 {}: {error}", link.display()))?;
    } else if link.exists() {
        return Err(format!(
            "{} 已存在且不是符号链接；为避免覆盖用户文件，拒绝自动替换",
            link.display()
        ));
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::symlink;
        let mut staging = link.as_os_str().to_os_string();
        staging.push(format!(".tmp-{}", std::process::id()));
        let staging = PathBuf::from(staging);
        symlink(&target, &staging)
            .and_then(|()| fs::rename(&staging, &link))
            .map_err(|error| {
                let _ = fs::remove_file(&staging);
                format!("无法建立模块链接 {}: {error}", link.display())
            })?;
    }
    Ok(link)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    fn config<'a>() -> BootConfig<'a> {
        BootConfig {
            profile: "desktop",
            profile_dir: Path::new("/home/pt/.dsh/profiles/desktop"),
            host: "127.0.0.1",
            desktop_version: "0.11.0",
            pnpm: None,
        }
    }

    #[test]
    fn boot_script_imports_the_upstream_subpaths_only() {
        let script = render_boot_script(&config());
        assert!(script.contains("from '@deepseek-ai/dsh/profile-boot'"));
        assert!(script.contains("from '@deepseek-ai/dsh-app-boot'"));
        assert!(script.contains("from '@deepseek-ai/dsh-launch-environment'"));
        assert!(script.contains("runProfile(") && script.contains("loadProfileDirectory("));
        assert!(script.contains("createLaunchEnvironmentSnapshot("));
        assert!(script.contains("{ userLayer: true }"));
        assert!(!script.contains("dshDesktop"));
        assert!(!script.contains("data-platform"));
    }

    #[test]
    fn boot_script_reads_configuration_from_the_environment() {
        let script = render_boot_script(&config());
        assert!(script.contains(&format!("JSON.parse(process.env.{BOOT_CONFIG_ENV})")));
        let payload = render_boot_config(
            &config(),
            Path::new("/home/pt/.dsh/dsh-tauri/boot/dsh-tauri.runtime.patch.json"),
        );
        for key in ["profileName", "profileDir", "runtimePatch", "host", "pnpm"] {
            assert!(payload.contains(key), "missing config key {key}");
        }
        let parsed: Value = serde_json::from_str(&payload).expect("valid boot config JSON");
        assert_eq!(parsed["profileName"], "desktop");
        assert_eq!(parsed["host"], "127.0.0.1");
        assert!(parsed["pnpm"].is_null());
        assert_eq!(parsed["runtimePatch"], "/home/pt/.dsh/dsh-tauri/boot/dsh-tauri.runtime.patch.json");
    }

    #[test]
    fn hostile_configuration_values_are_never_pasted_into_js_source() {
        let hostile = "\"; process.exit(1); // <script>";
        let custom = BootConfig {
            profile: hostile,
            profile_dir: Path::new(hostile),
            host: hostile,
            desktop_version: hostile,
            pnpm: None,
        };
        let script = render_boot_script(&custom);
        assert!(!script.contains(hostile), "no interpolation into generated JS");
        let payload = render_boot_config(&custom, Path::new(hostile));
        let parsed: Value = serde_json::from_str(&payload).expect("hostile values are JSON-escaped");
        assert_eq!(parsed["profileName"], hostile);
    }

    #[test]
    fn runtime_patch_is_loopback_only_and_has_no_lan_hosts() {
        let patch = render_runtime_patch("0.11.0");
        let value: Value = serde_json::from_str(&patch).expect("runtime patch must be JSON");
        let rows = value.as_array().expect("patch is a row array");
        assert_eq!(rows.len(), 3, "only host, connection and telemetry rows");
        assert_eq!(rows[0]["id"], "desktop-next-webserver");
        assert_eq!(rows[0]["config"]["host"], "127.0.0.1");
        assert_eq!(rows[0]["config"]["port"], 0);
        assert_eq!(rows[1]["id"], "connection");
        assert_eq!(rows[1]["config"]["trustedHosts"], serde_json::json!([]));
        assert_eq!(rows[2]["id"], "desktop-product-telemetry");
        assert_eq!(rows[2]["config"]["serviceName"], "deepseek-harness-desktop");
        assert_eq!(rows[2]["config"]["serviceVersion"], "0.11.0");
        for forbidden in ["172.18.", "172.20.", "192.168.", "0.0.0.0"] {
            assert!(!patch.contains(forbidden), "LAN address leaked: {forbidden}");
        }
        assert!(patch.contains("\"port\": 0"));
    }

    #[test]
    fn generated_files_are_written_atomically_and_are_idempotent() {
        let dir = std::env::temp_dir().join(format!("dsh-tauri-boot-test-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let content = render_boot_script(&config());
        let path = write_boot_script(&dir, &content).expect("write launcher");
        assert_eq!(path, dir.join(BOOT_FILE));
        assert_eq!(fs::read_to_string(&path).expect("read launcher"), content);
        let staging_name = format!("{BOOT_FILE}.tmp-{}", std::process::id());
        write_boot_script(&dir, &content).expect("idempotent write");
        assert!(fs::read_dir(&dir).expect("list dir").all(|entry| {
            entry.expect("entry").file_name() != std::ffi::OsStr::new(staging_name.as_str())
        }));
        let patch_path = write_runtime_patch(&dir, &render_runtime_patch("0.11.0")).expect("write patch");
        assert_eq!(patch_path, dir.join(PATCH_FILE));
        let _ = fs::remove_dir_all(&dir);
    }
}
